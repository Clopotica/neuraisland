export function t(key, vars) {
  const table = STR[state.lang] || STR.en;
  let s = table[key] ?? STR.en[key] ?? key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

// Pick the current language from a { en, ro } object (strings pass through).
export function L(obj, vars) {
  if (obj == null) return '';
  let s = typeof obj === 'string' ? obj : obj[state.lang] ?? obj.en ?? '';
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

export function levelName(lv) {
  return t('level' + lv);
}
